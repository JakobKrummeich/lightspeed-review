/**
 * The rule the whole module turns on. Both files would be mechanical on their
 * diff alone — one is a rename git scored 100%, the other pure re-indentation.
 */
test("guardrail wins over every mechanical rule", () => {
  const movedWorkflow = file(".github/workflows/release.yml", {
    status: "renamed",
    previousPath: ".github/workflows/publish.yml",
    similarity: 100,
    diff: [
      "diff --git a/.github/workflows/publish.yml b/.github/workflows/release.yml",
      "similarity index 100%",
    ].join("\n"),
  });
  const reindentedScript = file("scripts/deploy.sh", {
    insertions: 1,
    deletions: 1,
    diff: patch(
      "scripts/deploy.sh",
      ["@@ -3,3 +3,3 @@", "-  rsync -a build/ $TARGET", "+    rsync -a build/ $TARGET"].join("\n"),
    ),
  });

  assert.deepEqual(classifyFile(movedWorkflow), { mechanical: false, guardrail: true });
  assert.deepEqual(classifyFile(reindentedScript), { mechanical: false, guardrail: true });
});

