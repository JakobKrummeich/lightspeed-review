import { test } from "node:test";
import assert from "node:assert/strict";
import type { DiffFile } from "../src/diff-extract.ts";
import {
  GUARDRAIL_PATH_RULES,
  MECHANICAL_PATH_RULES,
  classifyFile,
  type ClassifyConfig,
  type PathRule,
} from "../src/classify.ts";

function file(path: string, overrides: Partial<DiffFile> = {}): DiffFile {
  return {
    path,
    status: "modified",
    diff: "",
    insertions: 0,
    deletions: 0,
    oversized: false,
    ...overrides,
  };
}

/** A patch with the `diff --git`/`index`/`---`/`+++` header a real one carries. */
function patch(path: string, body: string): string {
  return [
    `diff --git a/${path} b/${path}`,
    "index 1111111111111111111111111111111111111111..2222222222222222222222222222222222222222 100644",
    `--- a/${path}`,
    `+++ b/${path}`,
    body,
  ].join("\n");
}

function globs(overrides: Partial<ClassifyConfig> = {}): ClassifyConfig {
  return { mechanical: [], guardrail: [], ...overrides };
}

test("a rename git scored 100% identical is mechanical: nothing in it is a decision", () => {
  const renamed = file("app/models/orders/order.rb", {
    status: "renamed",
    previousPath: "app/models/order.rb",
    similarity: 100,
    diff: [
      "diff --git a/app/models/order.rb b/app/models/orders/order.rb",
      "similarity index 100%",
      "rename from app/models/order.rb",
      "rename to app/models/orders/order.rb",
    ].join("\n"),
  });

  assert.deepEqual(classifyFile(renamed), { mechanical: true, guardrail: false });
});

test("a rename that also changed lines is not mechanical — the change is the point", () => {
  const renamed = file("app/models/orders/order.rb", {
    status: "renamed",
    previousPath: "app/models/order.rb",
    similarity: 96,
    insertions: 4,
    deletions: 2,
    diff: [
      "diff --git a/app/models/order.rb b/app/models/orders/order.rb",
      "similarity index 96%",
      "rename from app/models/order.rb",
      "rename to app/models/orders/order.rb",
      "--- a/app/models/order.rb",
      "+++ b/app/models/orders/order.rb",
      "@@ -1,5 +1,7 @@",
      "-class Order",
      "+module Orders",
      "+  class Order",
    ].join("\n"),
  });

  assert.equal(classifyFile(renamed).mechanical, false);
});

