test("a whitespace-only reformat is mechanical: every line came back with its content", () => {
  const reformatted = file("orders/service.py", {
    insertions: 3,
    deletions: 3,
    diff: patch(
      "orders/service.py",
      [
        "@@ -1,6 +1,6 @@",
        " def total(order):",
        "-  subtotal = sum(line.amount for line in order.lines)",
        "-  tax = subtotal * TAX_RATE",
        "-  return subtotal + tax",
        "+    subtotal = sum(line.amount for line in order.lines)",
        "+    tax = subtotal * TAX_RATE",
        "+    return subtotal + tax",
      ].join("\n"),
    ),
  });

  assert.deepEqual(classifyFile(reformatted), { mechanical: true, guardrail: false });
});

