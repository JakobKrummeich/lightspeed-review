test("`*` stops at a separator, `**` crosses it, and the rest is literal", () => {
  const star = globs({ mechanical: ["docs/*.json"] });
  const globstar = globs({ mechanical: ["docs/**"] });
  const literal = globs({ mechanical: ["db/schema.rb"] });

  assert.equal(classifyFile(file("docs/orders.json"), star).mechanical, true);
  assert.equal(classifyFile(file("docs/api/orders.json"), star).mechanical, false);
  assert.equal(classifyFile(file("docs/api/orders.json"), globstar).mechanical, true);
  assert.equal(classifyFile(file("db/schema.rb"), literal).mechanical, true);
  assert.equal(classifyFile(file("app/db/schema.rb"), literal).mechanical, false);
});

/** A `**` between two segments has to swallow its own separator, or `docs/x.md` escapes it. */
test("a `**` in the middle of a glob matches no directory at all", () => {
  const nested = globs({ guardrail: ["app/**/secrets.rb"] });

  assert.equal(classifyFile(file("app/secrets.rb"), nested).guardrail, true);
  assert.equal(classifyFile(file("app/models/admin/secrets.rb"), nested).guardrail, true);
  assert.equal(classifyFile(file("app/models/admin/keys.rb"), nested).guardrail, false);
});

test("a glob's regex characters are literal, so a `.` is a dot and nothing else", () => {
  const configured = globs({ mechanical: ["CHANGELOG.md"] });

  assert.equal(classifyFile(file("CHANGELOGxmd"), configured).mechanical, false);
});

/** Mirrors `TEST_PATH_CONVENTIONS`: a rule that stopped claiming its own examples fails here. */
function claims(rules: readonly PathRule[], path: string): PathRule[] {
  return rules.filter((rule) => rule.pattern.test(path));
}

for (const [table, rules] of [
  ["guardrail", GUARDRAIL_PATH_RULES],
  ["mechanical", MECHANICAL_PATH_RULES],
] as const) {
  test(`every ${table} rule claims its own examples`, () => {
    for (const rule of rules) {
      for (const example of rule.examples) {
        assert.ok(claims(rules, example).includes(rule), `${rule.name} lost ${example}`);
      }
    }
  });

  test(`no ${table} rule claims a counterexample of any rule`, () => {
    for (const rule of rules) {
      for (const counterexample of rule.counterexamples) {
        const claimants = claims(rules, counterexample).map((claimant) => claimant.name);
        assert.deepEqual(claimants, [], `${counterexample} was claimed by ${claimants.join(", ")}`);
      }
    }
  });

  test(`every ${table} rule is the sole claimant of at least one example`, () => {
    for (const rule of rules) {
      const sole = rule.examples.filter((example) => claims(rules, example).length === 1);
      assert.ok(sole.length > 0, `${rule.name} claims nothing another rule does not`);
    }
  });
}

/** The contract in the module comment, checked rather than promised. */
test("no default rule names a path out of this repository", () => {
  for (const rule of [...GUARDRAIL_PATH_RULES, ...MECHANICAL_PATH_RULES]) {
    assert.doesNotMatch(rule.pattern.source, /src\\\/(browser|llm|ledger|rounds|commands|server)/);
  }
});
